import streamlit as st
import pandas as pd
import numpy as np
import joblib

model= joblib.load("Ev_blast.pkl")

st.title("Battery Health Prediction")

Battery_type=st.selectbox("Battery type")
Poor_Cell_Design=st.number_input("Poor Cell Design",min_value=0.0,max_value=1.0,step=1)
External_Abuse=st.selectbox("External Abuse")
Poor_Battery_Design=st.number_input("Poor Battery Design",min_value=0.0,max_value=1.0,step=1)
Short_Circuits=st.number_input("Short Circuits",min_value=0.0,max_value=1.0,step=1)
Temperature=st.number_input("Temperature")
Overcharge_Overdischarge=st.selectbox("Overcharge Overdischarge")
Battery_Maintenance=st.selectbox("Battery Maintenance")
Battery_Health=st.selectbox("Battery_Health")


df= pd.DataFrame({
    "Battery type": [Battery_type],
    "Poor Cell Design": [Poor_Cell_Design],
    "External Abuse": [External_Abuse],
    "Poor Battery Design": [Poor_Battery_Design],
    "Short Circuits": [Short_Circuits],
    "Temperature": [Temperature],
    "Overcharge Overdischarge": [Overcharge_Overdischarge],
    "Battery Maintenance": [Battery_Maintenance],
    "Battery_Health": [Battery_Health]

})

if st.button("Predict Battery Health"):
    prediction = model.predict(df)[0]

    if prediction == 0:
        st.write("Moderate")
    elif prediction == 1:
        st.write("Chance of Blast")
    elif prediction == 2:
        st.write("Blast")
    elif prediction == 3:
        st.write("Good")